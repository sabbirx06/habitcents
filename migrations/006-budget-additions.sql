-- Records new budget additions only; existing budget totals remain unchanged.
BEGIN;
CREATE TABLE budget_additions (
 addition_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
 budget_id INTEGER NOT NULL REFERENCES budgets(budget_id) ON DELETE CASCADE,
 amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
 source VARCHAR(255) NOT NULL CHECK (length(trim(source)) > 0),
 date DATE NOT NULL,
 request_key VARCHAR(64) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (user_id,request_key)
);
CREATE INDEX budget_additions_owner_budget_idx ON budget_additions(user_id,budget_id,addition_id DESC);
ALTER TABLE budget_additions ENABLE ROW LEVEL SECURITY;
COMMIT;
