-- HabitCents PostgreSQL / Supabase schema for a NEW empty database.
-- Historical MySQL schema.sql is deliberately unchanged. No reset/drop statements.
BEGIN;
CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    age INTEGER,
    current_streak INTEGER DEFAULT 0,
    highest_streak INTEGER DEFAULT 0
);
CREATE TABLE habits (
    habit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    habit_name VARCHAR(255) NOT NULL,
    difficulty_score INTEGER NOT NULL CHECK (difficulty_score BETWEEN 1 AND 10),
    category VARCHAR(50)
);
CREATE TABLE habit_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habit_id BIGINT NOT NULL REFERENCES habits(habit_id) ON DELETE CASCADE,
    date DATE NOT NULL,
    completed_status BOOLEAN DEFAULT true,
    streak_points_earned INTEGER,
    UNIQUE (habit_id, date)
);
CREATE TABLE physical_habits (
    habit_id BIGINT PRIMARY KEY REFERENCES habits(habit_id) ON DELETE CASCADE
);
CREATE TABLE spiritual_habits (
    habit_id BIGINT PRIMARY KEY REFERENCES habits(habit_id) ON DELETE CASCADE
);
CREATE TABLE healthy_habits (
    habit_id BIGINT PRIMARY KEY REFERENCES habits(habit_id) ON DELETE CASCADE
);
CREATE TABLE budgets (
    budget_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    total_budget NUMERIC(10,2) NOT NULL CHECK (total_budget >= 0),
    month INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    year INTEGER NOT NULL,
    UNIQUE (user_id, month, year)
);
CREATE TABLE expenses (
    expense_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    budget_id INTEGER REFERENCES budgets(budget_id) ON DELETE SET NULL,
    date DATE NOT NULL,
    description VARCHAR(255),
    category VARCHAR(32) NOT NULL DEFAULT 'uncategorized' CHECK (category IN ('transport','food','subscriptions','shopping','uncategorized')),
    amount NUMERIC(10,2) NOT NULL CHECK (amount >= 0)
);
CREATE TABLE savings_goals (
    goal_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    saved_amount NUMERIC(10,2) DEFAULT 0,
    target_amount NUMERIC(10,2) NOT NULL CHECK (target_amount > 0)
);
CREATE INDEX habits_user_idx ON habits(user_id);
CREATE INDEX expenses_user_date_idx ON expenses(user_id, date);
CREATE INDEX savings_user_idx ON savings_goals(user_id);
-- Only the trusted server database role accesses these tables. No browser policies.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE habits ENABLE ROW LEVEL SECURITY;
ALTER TABLE habit_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE physical_habits ENABLE ROW LEVEL SECURITY;
ALTER TABLE spiritual_habits ENABLE ROW LEVEL SECURITY;
ALTER TABLE healthy_habits ENABLE ROW LEVEL SECURITY;
ALTER TABLE budgets ENABLE ROW LEVEL SECURITY;
ALTER TABLE expenses ENABLE ROW LEVEL SECURITY;
ALTER TABLE savings_goals ENABLE ROW LEVEL SECURITY;
COMMIT;
